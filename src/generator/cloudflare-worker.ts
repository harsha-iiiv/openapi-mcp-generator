/** Runtime-relevant subset of a security scheme, embedded into the generated index.ts. */
interface RuntimeSecurityScheme {
  type: string;
  in?: string;
  name?: string;
  scheme?: string;
  tokenUrl?: string | null;
  /** OAuth2 only: the scheme declares a client credentials flow the Worker can fetch tokens with. */
  clientCredentials?: boolean;
}

/**
 * Build a name -> runtime-metadata map from the spec's security schemes, capturing only
 * what the generated `applyAuth` needs at runtime. The spec is dereferenced upstream, so
 * `$ref` entries are skipped (guarded by a `'type' in scheme` check).
 */
function buildRuntimeSecuritySchemes(
  securitySchemes: OpenAPIV3.ComponentsObject['securitySchemes']
): Record<string, RuntimeSecurityScheme> {
  const map: Record<string, RuntimeSecurityScheme> = {};
  const schemes = securitySchemes ?? {};
  for (const [name, raw] of Object.entries(schemes)) {
    if (!raw || typeof raw !== 'object' || !('type' in raw)) continue;
    const scheme = raw as OpenAPIV3.SecuritySchemeObject;
    if (scheme.type === 'apiKey') {
      map[name] = { type: 'apiKey', in: scheme.in, name: scheme.name };
    } else if (scheme.type === 'http') {
      // Normalize the scheme name (HTTP auth schemes are case-insensitive per
      // RFC 7235) so the generated runtime's `=== 'basic'` check matches specs
      // that write "Basic"/"Bearer".
      map[name] = { type: 'http', scheme: scheme.scheme?.toLowerCase() };
    } else if (scheme.type === 'oauth2') {
      // Only a client credentials flow lets the Worker fetch a token itself; every
      // other flow needs a token you already have (<SCHEME>_TOKEN).
      const clientCredentials = Boolean(scheme.flows?.clientCredentials);
      const tokenUrl = scheme.flows?.clientCredentials?.tokenUrl ?? null;
      map[name] = { type: 'oauth2', tokenUrl, clientCredentials };
    } else {
      // openIdConnect (bearer token from <SCHEME>_TOKEN) or any other type.
      map[name] = { type: scheme.type };
    }
  }
  return map;
}

